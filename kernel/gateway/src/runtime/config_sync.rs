#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_entries_exist() {
        let configs = builtin_configs();
        assert!(!configs.is_empty(), "at least one builtin config");
        for cfg in &configs {
            assert!(!cfg.rel_path.is_empty());
            assert!(!cfg.hash.is_empty());
            assert!(!cfg.content.is_empty());
        }
    }

    #[test]
    fn content_hash_is_deterministic() {
        let a = content_hash("hello");
        let b = content_hash("hello");
        assert_eq!(a, b);
    }

    #[test]
    fn sync_creates_configs() {
        let tmp =
            std::env::temp_dir().join(format!("aman-config-sync-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);

        sync_builtin_configs_to(&tmp).expect("sync should succeed");

        for cfg in builtin_configs() {
            let path = tmp.join(cfg.rel_path);
            assert!(path.exists(), "{} should exist", path.display());
        }

        assert!(tmp.join(".manifest.json").exists());

        let _ = std::fs::remove_dir_all(&tmp);
    }

    #[test]
    fn sync_preserves_user_modified_config() {
        let tmp = std::env::temp_dir().join(format!(
            "aman-config-sync-preserve-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&tmp);

        let configs = builtin_configs();
        let target = &configs[0];
        let target_path = tmp.join(target.rel_path);

        // First sync
        sync_builtin_configs_to(&tmp).expect("first sync");

        // Modify it
        let modified = target.content.to_owned() + "// user edit\n";
        std::fs::write(&target_path, &modified).expect("write modification");

        // Second sync — should preserve
        sync_builtin_configs_to(&tmp).expect("second sync");
        let after = std::fs::read_to_string(&target_path).unwrap();
        assert_eq!(after, modified, "user modification should be preserved");

        let _ = std::fs::remove_dir_all(&tmp);
    }

    #[test]
    fn sync_overwrites_unmodified_config() {
        let tmp = std::env::temp_dir().join(format!(
            "aman-config-sync-overwrite-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&tmp);

        let configs = builtin_configs();
        let target = &configs[0];
        let target_path = tmp.join(target.rel_path);

        // First sync
        sync_builtin_configs_to(&tmp).expect("first sync");
        let first = std::fs::read_to_string(&target_path).unwrap();
        assert_eq!(first, target.content);

        // Second sync — unchanged, should overwrite (no-op since content matches)
        sync_builtin_configs_to(&tmp).expect("second sync");
        let second = std::fs::read_to_string(&target_path).unwrap();
        assert_eq!(second, target.content);

        let _ = std::fs::remove_dir_all(&tmp);
    }
}

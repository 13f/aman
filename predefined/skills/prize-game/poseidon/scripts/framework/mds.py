"""
MDS matrix generation and verification for Poseidon.

Based on the official poseidon-tools implementation:
  https://github.com/khovratovich/poseidon-tools

Supports two MDS constructions:
  1. Cauchy: MDS[i][j] = 1/(i - t - j) mod p  (default for bounty)
  2. Plonky3 Circulant: MDS[i][j] = first_row[(j-i) % t]  (used in Plonky3)

Includes security verification (Algorithm 1/2/3, minpoly check) from
the official mds_matrix module.
"""

import random as _random

from framework.field import P as _P


# ── MDS Matrix Generation ─────────────────────────────────────────────


def generate_mds_matrix(t: int, prime: int = None) -> list:
    """Generate a t×t Cauchy MDS matrix over GF(prime).

    MDS[i][j] = 1/(i - t - j) mod prime

    This is the DEFAULT MDS for the Poseidon bounty.

    Args:
        t: State width (matrix dimension).
        prime: Field modulus (default: KoalaBear).

    Returns:
        t×t list-of-lists of integers in GF(prime).
    """
    if prime is None:
        prime = _P
    mds = []
    for i in range(t):
        row = []
        for j in range(t):
            diff = (i - t - j) % prime
            row.append(pow(diff, -1, prime))
        mds.append(row)
    return mds


def generate_circulant_mds_matrix(first_row: list, prime: int = None) -> list:
    """Generate a t×t circulant MDS matrix from its first row.

    MDS[i][j] = first_row[(j - i) % t] % prime

    This is the Plonky3-style MDS matrix.

    Args:
        first_row: First row of the circulant matrix (length t).
        prime: Field modulus.

    Returns:
        t×t list-of-lists of integers in GF(prime).
    """
    if prime is None:
        prime = _P
    t = len(first_row)
    return [
        [first_row[(j - i) % t] % prime for j in range(t)]
        for i in range(t)
    ]


def apply_mds(state: list, mds: list, prime: int = None) -> list:
    """Apply an MDS matrix to a state vector over GF(prime)."""
    if prime is None:
        prime = _P
    t = len(state)
    return [
        sum(mds[i][j] * state[j] for j in range(t)) % prime
        for i in range(t)
    ]



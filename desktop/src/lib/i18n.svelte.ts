/**
 * Translate a key into the current locale.
 * Falls back to English, then returns the key itself if missing.
 */
export function t(key: string): string {
  const bundle = current.code === "zhs" ? ZHS : EN;
  return bundle[key] ?? EN[key] ?? key;
}

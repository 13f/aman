//! Built-in plugin syncing.
//!
//! Syncs built-in plugins (embedded via `include_str!`) from the repo to the user's
//! local `~/.aman/plugins/` directory. Tracks content hashes so user modifications
//! are detected and preserved across updates.
//!
//! Follows the same pattern as [`super::skill_sync`].

use std::collections::HashMap;
use std::path::Path;

// ---------------------------------------------------------------------------
// Data types
// ---------------------------------------------------------------------------

/// A single built-in plugin embedded in the binary.
struct BuiltinPlugin {
    /// Display name for logging.
    name: &'static str,
    /// `(rel_path, precomputed_blake3_hex, content)` — one entry per file.
    files: Vec<(&'static str, &'static str, &'static str)>,
}

/// Manifest file at `~/.aman/.plugin-manifest.json`.
#[derive(serde::Serialize, serde::Deserialize)]
struct PluginManifest {
    version: u32,
    /// Map from `rel_path` → blake3 hex hash of the last-synced built-in content.
    hashes: HashMap<String, String>,
}

// ---------------------------------------------------------------------------
// Built-in plugin definitions (auto-generated by build.rs)
// ---------------------------------------------------------------------------

include!(concat!(env!("OUT_DIR"), "/builtin_plugins.rs"));

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn content_hash(content: &str) -> String {
    blake3::hash(content.as_bytes()).to_hex().to_string()
}

fn load_manifest(path: &Path) -> PluginManifest {
    std::fs::read_to_string(path)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or(PluginManifest { version: 1, hashes: HashMap::new() })
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/// Sync built-in plugins to `~/.aman/plugins/` (convenience wrapper).
///
/// See [`sync_builtin_plugins_to`] for full documentation.
pub fn sync_builtin_plugins() -> Result<(), Box<dyn std::error::Error>> {
    sync_builtin_plugins_to(&super::skill_sync::aman_data_dir())
}

/// Sync built-in plugins to a given data directory.
///
/// For each file of each built-in plugin:
/// - **New** (not in manifest) → created.
/// - **Unmodified** (user copy hash matches manifest) → overwritten with latest.
/// - **Modified** (user changed their copy) → preserved, logged at WARN level.
///
/// The manifest is updated with the *current built-in* hashes so future syncs
/// can correctly detect user modifications.
fn sync_builtin_plugins_to(data_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let plugins_dir = data_dir.join("plugins");
    std::fs::create_dir_all(&plugins_dir)?;

    let manifest_path = data_dir.join(".plugin-manifest.json");
    let prev_manifest = load_manifest(&manifest_path);

    let plugins = builtin_plugins();
    let mut new_hashes = HashMap::new();

    for plugin in &plugins {
        for &(rel_path, hash, content) in &plugin.files {
            let dest = plugins_dir.join(rel_path);

            // Ensure parent subdirectory exists.
            if let Some(parent) = dest.parent() {
                std::fs::create_dir_all(parent)?;
            }

            let user_modified = prev_manifest
                .hashes
                .get(rel_path)
                .map(|prev_hash| {
                    dest.exists()
                        && std::fs::read_to_string(&dest)
                            .ok()
                            .map(|current| content_hash(&current) != *prev_hash)
                            .unwrap_or(false)
                })
                .unwrap_or(false);

            if user_modified {
                tracing::warn!(
                    plugin = %plugin.name,
                    file = rel_path,
                    path = %dest.display(),
                    "built-in plugin file has local modifications — preserving user changes"
                );
                new_hashes.insert(rel_path.to_owned(), hash.to_owned());
                continue;
            }

            std::fs::write(&dest, content)?;
            tracing::info!(
                plugin = %plugin.name,
                file = rel_path,
                path = %dest.display(),
                "synced built-in plugin file"
            );
            new_hashes.insert(rel_path.to_owned(), hash.to_owned());
        }
    }

    let manifest = PluginManifest { version: 1, hashes: new_hashes };
    std::fs::write(&manifest_path, serde_json::to_string_pretty(&manifest)?)?;

    Ok(())
}

// ---------------------------------------------------------------------------
// Tests

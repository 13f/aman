#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn content_hash_is_deterministic() {
        let a = content_hash("hello");
        let b = content_hash("hello");
        assert_eq!(a, b);
    }

    #[test]
    fn content_hash_differs_for_different_content() {
        let a = content_hash("hello");
        let b = content_hash("world");
        assert_ne!(a, b);
    }

    #[test]
    fn sync_creates_plugins_in_dir() {
        let tmp = std::env::temp_dir().join(format!("aman-plugin-sync-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        let plugins_dir = tmp.join("plugins");

        sync_builtin_plugins_to(&tmp).expect("sync_to should succeed");

        // Verify all files exist
        for plugin in builtin_plugins() {
            for &(rel_path, _, _) in &plugin.files {
                let path = plugins_dir.join(rel_path);
                assert!(path.exists(), "{} should exist", path.display());
            }
        }

        // Manifest should exist
        assert!(tmp.join(".plugin-manifest.json").exists());

        let _ = std::fs::remove_dir_all(&tmp);
    }

    #[test]
    fn sync_preserves_user_modified_plugin() {
        let tmp = std::env::temp_dir().join(format!("aman-plugin-sync-preserve-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        let plugins_dir = tmp.join("plugins");

        let plugins = builtin_plugins();
        let target_plugin = &plugins[0];
        let target_file = &target_plugin.files[0];
        let target_path = plugins_dir.join(target_file.0);

        // First sync
        sync_builtin_plugins_to(&tmp).expect("first sync");

        // Modify it
        std::fs::write(&target_path, "# modified by user\n").expect("write modification");
        let modified_content = std::fs::read_to_string(&target_path).unwrap();

        // Second sync — should preserve modification
        sync_builtin_plugins_to(&tmp).expect("second sync");
        let after = std::fs::read_to_string(&target_path).unwrap();
        assert_eq!(after, modified_content, "user modification should be preserved");

        let _ = std::fs::remove_dir_all(&tmp);
    }

    #[test]
    fn sync_replaces_plugin_that_was_reverted_to_builtin() {
        let tmp = std::env::temp_dir().join(format!("aman-plugin-sync-revert-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        let plugins_dir = tmp.join("plugins");

        let plugins = builtin_plugins();
        let target_plugin = &plugins[0];
        let target_file = &target_plugin.files[0];
        let target_path = plugins_dir.join(target_file.0);

        // First sync creates all plugins
        sync_builtin_plugins_to(&tmp).expect("first sync");

        // Modify it
        std::fs::write(&target_path, "# modified\n").expect("write modification");

        // Second sync preserves modification
        sync_builtin_plugins_to(&tmp).expect("second sync");
        let after = std::fs::read_to_string(&target_path).unwrap();
        assert_eq!(after, "# modified\n", "modification still preserved");

        // Revert by writing the original built-in content
        std::fs::write(&target_path, target_file.2).expect("write reverted content");

        // Third sync: file now matches built-in (user "reverted").
        sync_builtin_plugins_to(&tmp).expect("third sync");

        let _ = std::fs::remove_dir_all(&tmp);
    }
}
